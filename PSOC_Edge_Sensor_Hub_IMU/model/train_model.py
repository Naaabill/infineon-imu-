#!/usr/bin/env python3
"""Train a tiny two-feature IMU rest/motion classifier (Python stdlib only)."""
from __future__ import annotations
import csv, json, math
from collections import defaultdict
from pathlib import Path
ROOT=Path(__file__).resolve().parent
DATA=ROOT/'windows_2s_binary.csv'; HEADER=ROOT/'imu_motion_model.h'; REPORT=ROOT/'training_report.json'
N=100

def load_windows():
    groups=defaultdict(list)
    with DATA.open(newline='',encoding='utf-8-sig') as f:
        for row in csv.DictReader(f): groups[row['window_id']].append(row)
    result=[]
    for wid,rows in groups.items():
        if len(rows)!=N: raise ValueError(f'{wid}: expected {N} samples, got {len(rows)}')
        rows.sort(key=lambda r:int(r['sample_in_window']))
        t=[int(r['t_ms']) for r in rows]
        if any(b-a!=20 for a,b in zip(t,t[1:])): raise ValueError(f'{wid}: sample interval is not 20 ms')
        vals=[[float(r[k]) for k in ('ax_mps2','ay_mps2','az_mps2','gx_rad_s','gy_rad_s','gz_rad_s')] for r in rows]
        a=[sum(v[i]*v[i] for i in range(3)) for v in vals]
        g=[sum(v[i]*v[i] for i in range(3,6)) for v in vals]
        mean=sum(a)/N
        result.append({'id':wid,'source':rows[0]['source_label'],'label':'repos' if rows[0]['label']=='repos' else 'mouvement',
                       'acc_variance':sum((v-mean)**2 for v in a)/N,'gyro_energy':sum(g)/N})
    if not result: raise ValueError('No windows found')
    return result

def gini(rows):
    if not rows:return 0.0
    p=sum(x['label']=='repos' for x in rows)/len(rows)
    return 1-p*p-(1-p)*(1-p)

def fit_threshold(rows,key):
    vals=sorted({x[key] for x in rows})
    best=None
    for a,b in zip(vals,vals[1:]):
        t=(a+b)/2
        low=[x for x in rows if x[key]<=t]; high=[x for x in rows if x[key]>t]
        # low predicts rest, high predicts movement
        err=sum(x['label']!='repos' for x in low)+sum(x['label']!='mouvement' for x in high)
        score=(len(low)*gini(low)+len(high)*gini(high))/len(rows)
        cand=(score,err,t)
        if best is None or cand<best:best=cand
    if best is None:raise ValueError(f'Could not split on {key}')
    return best[2]

def predict(x,ta,tg):
    return 'mouvement' if x['acc_variance']>ta or x['gyro_energy']>tg else 'repos'

def main():
    rows=load_windows(); by=defaultdict(list)
    for x in rows:by[x['source']].append(x)
    train=[];test=[]
    for seq in by.values():
        n=max(1,math.ceil(len(seq)*.2));train.extend(seq[:-n]);test.extend(seq[-n:])
    ta=fit_threshold(train,'acc_variance');tg=fit_threshold(train,'gyro_energy')
    confusion={a:{p:0 for p in ('repos','mouvement')} for a in ('repos','mouvement')}
    for x in test:confusion[x['label']][predict(x,ta,tg)]+=1
    correct=sum(confusion[k][k] for k in confusion)
    fa=fit_threshold(rows,'acc_variance');fg=fit_threshold(rows,'gyro_energy');full_correct=sum(predict(x,fa,fg)==x['label'] for x in rows)
    HEADER.write_text(f'''/* Generated by train_model.py. Do not edit by hand.\n * 2s at 50Hz; acceleration magnitude-squared variance and mean gyro energy.\n */\n#ifndef IMU_MOTION_MODEL_H\n#define IMU_MOTION_MODEL_H\n#define IMU_MODEL_WINDOW_SAMPLES 100u\n#define IMU_MODEL_REPOS 0\n#define IMU_MODEL_MOUVEMENT 1\n#define IMU_MODEL_ACC_VARIANCE_THRESHOLD {fa:.9g}f\n#define IMU_MODEL_GYRO_ENERGY_THRESHOLD {fg:.9g}f\nstatic inline int imu_motion_model_predict(float acc_variance, float gyro_energy)\n{{\n    return ((acc_variance > IMU_MODEL_ACC_VARIANCE_THRESHOLD) ||\n            (gyro_energy > IMU_MODEL_GYRO_ENERGY_THRESHOLD)) ?\n           IMU_MODEL_MOUVEMENT : IMU_MODEL_REPOS;\n}}\nstatic inline const char *imu_motion_model_label(int prediction)\n{{\n    return (prediction == IMU_MODEL_REPOS) ? "repos" : "mouvement";\n}}\n#endif /* IMU_MOTION_MODEL_H */\n''',encoding='utf-8',newline='\n')
    rep={'features':['population variance of ax^2+ay^2+az^2 over 100 samples','mean gx^2+gy^2+gz^2 over 100 samples'],'window_samples':N,'sample_rate_hz':50,'windows_total':len(rows),'windows_train':len(train),'windows_temporal_holdout':len(test),'temporal_holdout_accuracy':correct/len(test),'training_accuracy_all_windows':full_correct/len(rows),'temporal_holdout_confusion':confusion,'thresholds_temporal_holdout':{'acc_variance':ta,'gyro_energy':tg},'thresholds_final_all_data':{'acc_variance':fa,'gyro_energy':fg},'class_counts':{c:sum(x['label']==c for x in rows) for c in ('repos','mouvement')},'source_window_counts':{k:len(v) for k,v in by.items()},'warning':'Only three continuous capture sessions are available; this holdout score does not prove performance on new sessions. The rest capture includes one orientation only.'}
    REPORT.write_text(json.dumps(rep,indent=2,ensure_ascii=False)+'\n',encoding='utf-8');print(json.dumps(rep,indent=2,ensure_ascii=False));print('Generated',HEADER)
if __name__=='__main__':main()