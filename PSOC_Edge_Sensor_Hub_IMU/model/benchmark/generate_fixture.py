#!/usr/bin/env python3
"""Generate a portable, quantized C fixture from the prepared IMU CSV."""
import argparse
import csv
from collections import OrderedDict
from pathlib import Path


FIELDS = ("ax_mps2", "ay_mps2", "az_mps2", "gx_rad_s", "gy_rad_s", "gz_rad_s")
ACC_SCALE = 1000.0 / 9.80665  # int16 values represent milli-g
GYRO_SCALE = 1000.0          # int16 values represent milli-rad/s


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", type=Path, help="prepared windows CSV")
    parser.add_argument("--output", type=Path, required=True, help="output C header")
    args = parser.parse_args()

    windows = OrderedDict()
    with args.csv.open(newline="", encoding="utf-8-sig") as stream:
        for row in csv.DictReader(stream):
            name = row["window_id"]
            samples = windows.setdefault(name, [])
            values = [round(float(row[field]) * (ACC_SCALE if i < 3 else GYRO_SCALE))
                      for i, field in enumerate(FIELDS)]
            if any(value < -32768 or value > 32767 for value in values):
                raise ValueError(f"int16 overflow in {name}: {values}")
            samples.append(values)
            if len(samples) > 100:
                raise ValueError(f"more than 100 samples in {name}")

    if not windows or any(len(samples) != 100 for samples in windows.values()):
        raise ValueError("every fixture window must contain exactly 100 samples")

    lines = [
        "/* Generated by generate_fixture.py; do not edit by hand. */",
        "#ifndef IMU_BENCHMARK_FIXTURE_H",
        "#define IMU_BENCHMARK_FIXTURE_H",
        "#include <stdint.h>",
        "#define IMU_BENCH_WINDOW_COUNT %du" % len(windows),
        "#define IMU_BENCH_SAMPLES_PER_WINDOW 100u",
        "/* axes: ax, ay, az in milli-g; gx, gy, gz in milli-rad/s */",
        "typedef struct { int16_t axis[6]; } imu_bench_sample_t;",
        "static const imu_bench_sample_t imu_bench_fixture[IMU_BENCH_WINDOW_COUNT]"
        "[IMU_BENCH_SAMPLES_PER_WINDOW] = {",
    ]
    for name, samples in windows.items():
        label = 0 if name.startswith("repos_") else 1
        lines.append("    { /* %s: %s */" % (name, "repos" if label == 0 else "mouvement"))
        lines.extend("        {{%s}}," % ", ".join(map(str, values)) for values in samples)
        lines.append("    },")
    labels = [0 if name.startswith("repos_") else 1 for name in windows]
    lines.extend([
        "};",
        "static const uint8_t imu_bench_labels[IMU_BENCH_WINDOW_COUNT] = {",
        "    " + ", ".join(map(str, labels)),
        "};",
        "#endif /* IMU_BENCHMARK_FIXTURE_H */",
        "",
    ])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(windows)} windows ({len(windows) * 100} samples) in {args.output}")


if __name__ == "__main__":
    main()
